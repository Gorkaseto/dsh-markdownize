// Bundles the third-party converters into vendor/ so the plugin has no runtime dependencies.
// dsh installs local plugins as `link:` symlinks, and pnpm never installs a linked package's
// dependencies, so importing 'jszip' etc. directly fails. Run after changing dependency versions:
//   npm install && npm run build
import { build } from 'esbuild'

const banner = `// Generated by build-vendor.mjs; do not edit.
import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);`

const entries = {
  // Loaded eagerly by convert.js.
  deps: `export { default as JSZip } from 'jszip'
export { default as mammoth } from 'mammoth'
export { default as TurndownService } from 'turndown'
export { gfm } from 'turndown-plugin-gfm'
export { XMLParser } from 'fast-xml-parser'
export { default as ExcelJS } from 'exceljs'`,
  // pdf.js is large; convert.js imports it lazily, only for PDFs.
  unpdf: `export { extractText, getDocumentProxy } from 'unpdf'`,
}

for (const [name, contents] of Object.entries(entries)) {
  await build({
    stdin: { contents, resolveDir: import.meta.dirname, sourcefile: `${name}-entry.js` },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    minify: true,
    legalComments: 'linked',
    banner: { js: banner },
    outfile: `vendor/${name}.js`,
    logLevel: 'warning',
  })
}
